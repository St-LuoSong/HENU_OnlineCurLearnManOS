CREATE TABLE practice_session (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    knowledge_point_id BIGINT NULL,
    title VARCHAR(255) NOT NULL,
    state VARCHAR(24) NOT NULL DEFAULT 'LEARNING',
    current_grade VARCHAR(2) NOT NULL DEFAULT 'C',
    consecutive_failures INT NOT NULL DEFAULT 0,
    current_question_id BIGINT NULL,
    current_transfer TINYINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_practice_session_user (user_id, updated_at),
    CONSTRAINT fk_practice_session_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_practice_session_subject FOREIGN KEY (subject_id) REFERENCES subject (id),
    CONSTRAINT fk_practice_session_point FOREIGN KEY (knowledge_point_id) REFERENCES knowledge_point (id),
    CONSTRAINT fk_practice_session_question FOREIGN KEY (current_question_id) REFERENCES question (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE practice_message (
    id BIGINT NOT NULL AUTO_INCREMENT,
    session_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    message_type VARCHAR(24) NOT NULL,
    content MEDIUMTEXT NOT NULL,
    question_id BIGINT NULL,
    provider_code VARCHAR(32) NULL,
    model VARCHAR(128) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_practice_message_session (session_id, id),
    CONSTRAINT fk_practice_message_session
        FOREIGN KEY (session_id) REFERENCES practice_session (id)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE practice_answer (
    id BIGINT NOT NULL AUTO_INCREMENT,
    session_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    knowledge_point_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    is_transfer TINYINT NOT NULL DEFAULT 0,
    answer_content VARCHAR(2000) NOT NULL,
    is_correct TINYINT NOT NULL,
    grade VARCHAR(2) NOT NULL,
    error_type VARCHAR(32) NULL,
    error_label VARCHAR(64) NULL,
    feedback VARCHAR(2000) NULL,
    consecutive_failures INT NOT NULL DEFAULT 0,
    answered_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_practice_answer_session (session_id, id),
    KEY idx_practice_answer_question (question_id, answered_at),
    CONSTRAINT fk_practice_answer_session
        FOREIGN KEY (session_id) REFERENCES practice_session (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_practice_answer_question FOREIGN KEY (question_id) REFERENCES question (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

