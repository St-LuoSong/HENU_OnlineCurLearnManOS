CREATE TABLE learning_goal (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    subject_id BIGINT NULL,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(1000) NULL,
    target_date DATE NULL,
    priority VARCHAR(16) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    completed_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_learning_goal_user (user_id, status),
    KEY idx_learning_goal_subject (subject_id),
    CONSTRAINT fk_learning_goal_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_learning_goal_subject FOREIGN KEY (subject_id) REFERENCES subject (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE learning_task (
    id BIGINT NOT NULL AUTO_INCREMENT,
    goal_id BIGINT NULL,
    user_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(1000) NULL,
    category VARCHAR(32) NULL,
    due_at DATETIME(3) NULL,
    priority VARCHAR(16) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(16) NOT NULL DEFAULT 'TODO',
    completed_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_learning_task_user (user_id, status, due_at),
    KEY idx_learning_task_goal (goal_id),
    CONSTRAINT fk_learning_task_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_learning_task_goal FOREIGN KEY (goal_id) REFERENCES learning_goal (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE learning_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    subject_id BIGINT NULL,
    knowledge_point_id BIGINT NULL,
    resource_id BIGINT NULL,
    record_type VARCHAR(32) NOT NULL,
    duration_minutes INT NOT NULL DEFAULT 0,
    score DECIMAL(5, 2) NULL,
    mastered TINYINT NOT NULL DEFAULT 0,
    remark VARCHAR(1000) NULL,
    recorded_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_learning_record_user (user_id, recorded_at),
    KEY idx_learning_record_subject (subject_id, knowledge_point_id),
    CONSTRAINT fk_learning_record_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_learning_record_subject FOREIGN KEY (subject_id) REFERENCES subject (id),
    CONSTRAINT fk_learning_record_point FOREIGN KEY (knowledge_point_id) REFERENCES knowledge_point (id),
    CONSTRAINT fk_learning_record_resource FOREIGN KEY (resource_id) REFERENCES learning_resource (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE student_progress (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    knowledge_point_id BIGINT NOT NULL,
    current_grade VARCHAR(2) NOT NULL DEFAULT 'C',
    attempt_count INT NOT NULL DEFAULT 0,
    correct_count INT NOT NULL DEFAULT 0,
    mastered TINYINT NOT NULL DEFAULT 0,
    transfer_passed TINYINT NOT NULL DEFAULT 0,
    last_activity DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_student_progress_point (user_id, knowledge_point_id),
    KEY idx_student_progress_subject (user_id, subject_id),
    CONSTRAINT fk_student_progress_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_student_progress_subject FOREIGN KEY (subject_id) REFERENCES subject (id),
    CONSTRAINT fk_student_progress_point FOREIGN KEY (knowledge_point_id) REFERENCES knowledge_point (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
