CREATE TABLE practice_set (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    knowledge_point_id BIGINT NULL,
    title VARCHAR(255) NOT NULL,
    billing_mode VARCHAR(16) NOT NULL DEFAULT 'STANDARD',
    status VARCHAR(16) NOT NULL DEFAULT 'IN_PROGRESS',
    question_count INT NOT NULL DEFAULT 0,
    answered_count INT NOT NULL DEFAULT 0,
    correct_count INT NOT NULL DEFAULT 0,
    score INT NULL,
    duration_seconds INT NULL,
    started_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    submitted_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_practice_set_user (user_id, created_at),
    KEY idx_practice_set_subject (user_id, subject_id, created_at),
    KEY idx_practice_set_status (user_id, status),
    CONSTRAINT fk_practice_set_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_practice_set_subject FOREIGN KEY (subject_id) REFERENCES subject (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE practice_set_item (
    id BIGINT NOT NULL AUTO_INCREMENT,
    set_id BIGINT NOT NULL,
    seq INT NOT NULL,
    question_type VARCHAR(24) NOT NULL,
    stem MEDIUMTEXT NOT NULL,
    options_json TEXT NULL,
    correct_answer MEDIUMTEXT NOT NULL,
    explanation MEDIUMTEXT NULL,
    student_answer MEDIUMTEXT NULL,
    is_correct TINYINT NULL,
    awarded_score INT NULL,
    max_score INT NOT NULL DEFAULT 10,
    ai_feedback TEXT NULL,
    error_type VARCHAR(64) NULL,
    answered_at DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_practice_set_item_seq (set_id, seq),
    KEY idx_practice_set_item_set (set_id),
    CONSTRAINT fk_practice_set_item_set FOREIGN KEY (set_id) REFERENCES practice_set (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
